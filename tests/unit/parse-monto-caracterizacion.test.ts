/**
 * Cada lector devuelve lo suyo ante una entrada sin número: `undefined`, `null` o `NaN`.
 * Se comparan tal cual, sin unificar: esa diferencia es parte de lo que se caracteriza.
 */
function medir(fn: (s: string) => unknown, entrada: string): unknown {
  const v = fn(entrada);
  return typeof v === "number" && Number.isNaN(v) ? "NaN" : v;
}

